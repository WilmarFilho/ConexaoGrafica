    <h1>Política de Privacidade e Tratamento de Dados</h1>
    <p class="meta">Versão 1.0 · vigente desde 16 de setembro de 2026 · Responsável: Conexão Editora (Pubcon Publicações Exclusivas, CNPJ 19.674.533/0001-87)</p>

    <p>O Hub Editora é o sistema interno de expedição da editora. Ele reúne os pedidos das nossas lojas (site próprio, páginas de venda e Amazon) para preparar, postar e acompanhar as entregas. Esta política descreve como os dados pessoais dos compradores são coletados, usados, guardados, compartilhados e descartados, em conformidade com a LGPD (Lei 13.709/2018) e com a Política de Proteção de Dados da Amazon.</p>

    <h2>1. Quais dados coletamos</h2>
    <p>Apenas o necessário para entregar o pedido: número do pedido, itens e valores, nome do destinatário, endereço de entrega, telefone e CPF ou CNPJ (exigido pelas transportadoras). Não coletamos dados de pagamento: eles ficam com o meio de pagamento de cada canal.</p>

    <h2>2. Para que usamos</h2>
    <ul>
        <li>Compor a fila de expedição e conferir os pedidos.</li>
        <li>Emitir a etiqueta de postagem e contratar o frete.</li>
        <li>Informar ao canal de venda que o pedido foi enviado, com o código de rastreio.</li>
        <li>Atender o comprador em caso de dúvida, extravio ou devolução.</li>
    </ul>
    <p>Não usamos os dados para marketing, perfilamento ou qualquer outra finalidade.</p>

    <h2>3. Onde e como guardamos</h2>
    <p>Em servidor próprio localizado no Brasil, com acesso exclusivamente por HTTPS. O banco de dados usa criptografia em repouso, as credenciais de integração são armazenadas cifradas e o acesso ao servidor é feito apenas por chave criptográfica. Cada pessoa da equipe tem login individual com autenticação em dois fatores, e toda ação sobre um pedido fica registrada em trilha de auditoria com autor e data.</p>

    <h2>4. Com quem compartilhamos</h2>
    <table>
        <tr><th>Destinatário</th><th>O que recebe</th><th>Para quê</th></tr>
        <tr><td>Melhor Envio (plataforma de postagem)</td><td>Nome, endereço, documento e telefone do destinatário</td><td>Emissão da etiqueta e contratação do frete</td></tr>
        <tr><td>Transportadora (Correios ou outra escolhida no frete)</td><td>Dados impressos na etiqueta</td><td>Entrega do pacote</td></tr>
        <tr><td>Bling (ERP)</td><td>Pedido e código de rastreio</td><td>Conciliação e emissão de nota fiscal quando exigida</td></tr>
    </table>
    <p>Nenhum outro compartilhamento. Não vendemos nem cedemos dados a terceiros.</p>

    <h2>5. Por quanto tempo guardamos</h2>
    <p>Os dados pessoais dos compradores da Amazon são apagados automaticamente <strong>30 dias após o envio do pedido</strong>. Depois disso permanecem apenas o número do pedido, os itens, os valores, a cidade e o estado de destino e o código de rastreio, para fins fiscais, contábeis e de garantia. Para os demais canais, os dados são mantidos pelo prazo necessário ao atendimento do pedido e às obrigações legais.</p>

    <h2>6. Segurança e incidentes</h2>
    <p>Mantemos plano de resposta a incidentes com contenção em até 4 horas e comunicação aos parceiros afetados, incluindo a Amazon, em até 24 horas da detecção. Os registros de auditoria são revisados a cada 15 dias e mantidos por no mínimo 12 meses. Vulnerabilidades são verificadas periodicamente e corrigidas conforme sua severidade.</p>

    <h2>7. Direitos do titular</h2>
    <p>O comprador pode solicitar confirmação, acesso, correção ou eliminação dos seus dados, nos termos da LGPD, pelo canal abaixo. Pedidos são atendidos em até 15 dias.</p>

    <h2>8. Contato</h2>
    <p>Encarregado pelo tratamento de dados: Conexão Editora · <a href="mailto:comercial@conexaopro.com.br">comercial@conexaopro.com.br</a>.</p>

